#!/usr/bin/env python3
"""
custom-mlops-triage.py - Wazuh integration: ask the ML API about every alert

How it works:
  1. Wazuh runs this script for each alert and gives it the alert file path.
  2. We read rule.description and POST it to the Flask API (/predict).
  3. If the model says "malicious" (prediction = 1), we inject a NEW event
     into Wazuh. A custom rule (local_rules_snippet.xml) turns that event into
     a high-level alert. The original alert is not modified: Wazuh integrations
     cannot change an alert after it was generated.
  4. If the API is down or answers badly, we log the problem and exit quietly,
     so Wazuh itself is never disturbed.
"""
import json
import os
import sys
import time
from socket import AF_UNIX, SOCK_DGRAM, socket
from urllib import error, parse, request

LOG_FILE = os.getenv("MLOPS_LOG_FILE", "/var/ossec/logs/integrations.log")
SOCKET_ADDR = os.getenv("WAZUH_QUEUE_SOCKET", "/var/ossec/queue/sockets/queue")
DEFAULT_URL = os.getenv("MLOPS_API_URL", "http://127.0.0.1:5000/predict")
TIMEOUT_SECONDS = 5
MAX_LENGTH = 5000            # the API rejects longer texts
INTEGRATION = "mlops_triage"


def log(message):
    """Append a line to Wazuh's integrations log (never crash because of logging)."""
    line = f"{time.strftime('%Y-%m-%d %H:%M:%S')} {INTEGRATION}: {message}\n"
    try:
        with open(LOG_FILE, "a", encoding="utf-8") as handle:
            handle.write(line)
    except OSError:
        sys.stderr.write(line)


def find_api_url(argv):
    """Wazuh passes: alert_file, api_key, hook_url. We take the first http(s) argument."""
    for arg in argv[1:]:
        if arg.startswith(("http://", "https://")):
            return arg
    return DEFAULT_URL


def classify(url, text):
    """Send the text to the API and return its JSON answer."""
    if parse.urlparse(url).scheme not in ("http", "https"):
        raise ValueError(f"unsupported URL scheme: {url}")
    body = json.dumps({"rule_description": text[:MAX_LENGTH]}).encode("utf-8")
    req = request.Request(url, data=body, headers={"Content-Type": "application/json"})
    with request.urlopen(req, timeout=TIMEOUT_SECONDS) as response:  # nosec B310
        return json.loads(response.read().decode("utf-8"))


def send_to_wazuh(event, agent):
    """Inject an event into Wazuh's queue so that rules can analyse it."""
    message = json.dumps(event)
    if not agent or agent.get("id") == "000":
        payload = f"1:{INTEGRATION}:{message}"
    else:
        location = f"[{agent.get('id')}] ({agent.get('name')}) {agent.get('ip', 'any')}"
        location = location.replace("|", "||").replace(":", "|:")
        payload = f"1:{location}->{INTEGRATION}:{message}"
    sock = socket(AF_UNIX, SOCK_DGRAM)
    try:
        sock.connect(SOCKET_ADDR)
        sock.send(payload.encode())
    finally:
        sock.close()


def is_own_event(alert):
    """
    True if this alert was generated by our own injected event.
    In a real Wazuh alert the injected JSON fields are stored under "data", and
    our custom rules (local_rules_snippet.xml) belong to the group "mlops".
    Without this check the integration could trigger itself in an endless loop.
    """
    data = alert.get("data") if isinstance(alert.get("data"), dict) else {}
    groups = alert.get("rule", {}).get("groups", [])
    return (
        alert.get("integration") == INTEGRATION or INTEGRATION in alert
        or data.get("integration") == INTEGRATION or INTEGRATION in data
        or "mlops" in groups
    )


def main():
    if len(sys.argv) < 2:
        log("no alert file given, nothing to do")
        return

    try:
        with open(sys.argv[1], encoding="utf-8") as handle:
            alert = json.load(handle)
    except (OSError, ValueError) as exc:
        log(f"cannot read alert file: {exc}")
        return

    # Loop protection: never triage the alerts that this integration created itself
    if is_own_event(alert):
        return

    rule = alert.get("rule", {})
    description = rule.get("description")
    if not isinstance(description, str) or not description.strip():
        log("alert has no rule.description, skipped")
        return

    try:
        answer = classify(find_api_url(sys.argv), description)
        prediction = int(answer["prediction"])
    except (error.URLError, TimeoutError, OSError) as exc:
        log(f"API unreachable ({exc}); alert {rule.get('id')} left untouched")
        return
    except (ValueError, KeyError, TypeError) as exc:
        log(f"unexpected API answer ({exc}); alert {rule.get('id')} left untouched")
        return

    log(f"rule {rule.get('id')} -> prediction={prediction} probability={answer.get('probability')}")

    if prediction == 1:
        event = {
            "integration": INTEGRATION,
            INTEGRATION: {
                "prediction": prediction,
                "probability": answer.get("probability"),
                "source_rule_id": rule.get("id"),
                "source_rule_level": rule.get("level"),
                "source_description": description,
            },
        }
        try:
            send_to_wazuh(event, alert.get("agent"))
        except OSError as exc:
            log(f"cannot write to the Wazuh queue: {exc}")


if __name__ == "__main__":
    main()